"""Summarise a block of Claude live-model runs (`make test-e2e`) from its
committed records — the only source of the numbers it prints.

    uv run python scripts/experiment/claude_e2e_report.py \
        scripts/experiment/runs/claude-e2e/<block> [--out <block>/SUMMARY.md]

Reads <block>/runs.jsonl (one record per run, written by
tests/e2e/test_claude_live.py) and prints a Markdown summary: pass count per
task out of its runs, median cost and turns per run, total cost, and every
failed or invalid run with its first missing rung and the record's own error
fields. The pre-registration is scripts/experiment/CLAUDE_E2E.md.
"""

import argparse
import json
import statistics
import sys
from pathlib import Path

TASK_ORDER = (
    "flights_dashboard", "space_dashboard", "alerting_space", "fix_rule_threshold",
    # block "toolboxes" (2026-10-27, D61)
    "case_comment", "exception_item", "synthetic_param", "stream_fork", "agent_policy",
    "kibana_status", "delete_one_dashboard",
)


def load(block):
    path = Path(block) / "runs.jsonl"
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def _median(values):
    values = [v for v in values if v is not None]
    return statistics.median(values) if values else None


def _usd(v):
    return "n/a" if v is None else f"${v:.4f}"


def _num(v):
    if v is None:
        return "n/a"
    return f"{v:g}" if isinstance(v, float) else str(v)


def _cause(r):
    parts = []
    if not r.get("valid"):
        reasons = []
        if r.get("harness_error"):
            reasons.append(f"harness error {r['harness_error']}")
        if r.get("key_in_transcript"):
            reasons.append("API key in output")
        if r.get("non_server_tools"):
            reasons.append(f"offered non-server tools {r['non_server_tools']}")
        if r.get("permission_denials"):
            reasons.append(f"{r['permission_denials']} permission denial(s)")
        parts.append("invalid: " + ("; ".join(reasons) or "no result event"))
    if r.get("first_missing"):
        parts.append(f"first missing rung `{r['first_missing']}`")
    if r.get("timed_out"):
        parts.append("timed out")
    if r.get("is_error"):
        parts.append(f"CLI result `{r.get('terminal_reason')}`")
    if r.get("default_space_contamination"):
        parts.append("marker object in the default space")
    return "; ".join(parts) or "unknown"


# Blocks whose tasks were committed together with their records: nothing shows
# the tasks were fixed before the results, so the summary must not point at
# them as a pre-registration (CLAUDE_E2E.md says why each is kept).
NOT_PREREGISTERED = {
    "counted-2026-10-27-toolboxes": (
        "Generated by `scripts/experiment/claude_e2e_report.py` from `runs.jsonl` in this "
        "directory. **Not pre-registered**: block \"toolboxes\" of "
        "`scripts/experiment/CLAUDE_E2E.md` was committed with these records (`8bf24fe`), "
        "so these runs are the provenance of the replay transcripts converted from them, "
        "not a pre-registered result."
    ),
}


def render(records, block_name):
    tasks = [t for t in TASK_ORDER if any(r["task"] == t for r in records)]
    tasks += sorted({r["task"] for r in records} - set(tasks))
    costs = [r.get("total_cost_usd") for r in records]
    lines = [
        f"# Claude live-model runs: `{block_name}`",
        "",
        NOT_PREREGISTERED.get(
            block_name,
            "Generated by `scripts/experiment/claude_e2e_report.py` from `runs.jsonl` in this "
            "directory; the pre-registration is `scripts/experiment/CLAUDE_E2E.md`.",
        ),
        "",
        f"- Runs: {len(records)}; valid: {sum(1 for r in records if r.get('valid'))}",
        "- Model requested: "
        + ", ".join(f"`{m}`" for m in sorted({r.get('model_requested') for r in records})),
        "- Models reported by the CLI: "
        + ", ".join(f"`{m}`" for m in sorted({m for r in records for m in r.get("models_reported") or []})),
        "- Claude Code: " + ", ".join(sorted({str(r.get("claude_cli")) for r in records})),
        "- Kibana: " + ", ".join(sorted({str(r.get("kibana_version")) for r in records})),
        "- Server commit: "
        + ", ".join(sorted({f"{r.get('git_sha')}{' (src dirty)' if r.get('server_dirty') else ''}" for r in records})),
        f"- Runs with the API key in their output: {sum(1 for r in records if r.get('key_in_transcript'))}",
        f"- Total cost: {_usd(sum(c for c in costs if c is not None))}; "
        f"median per run: {_usd(_median(costs))}; "
        f"median turns per run: {_num(_median([r.get('num_turns') for r in records]))}",
        "",
        "| Task | Passed | Median cost | Median turns | Median tool calls | Median wall s |",
        "|---|---|---|---|---|---|",
    ]
    for t in tasks:
        rs = [r for r in records if r["task"] == t]
        passed = sum(1 for r in rs if r.get("valid") and r.get("passed"))
        lines.append(
            f"| `{t}` | {passed}/{len(rs)} | {_usd(_median([r.get('total_cost_usd') for r in rs]))} "
            f"| {_num(_median([r.get('num_turns') for r in rs]))} "
            f"| {_num(_median([r.get('n_tool_calls') for r in rs]))} "
            f"| {_num(_median([r.get('wall_s') for r in rs]))} |"
        )
    failed = [r for r in records if not (r.get("valid") and r.get("passed"))]
    lines += ["", "## Failed or invalid runs", ""]
    if not failed:
        lines.append("None.")
    for r in failed:
        lines.append(
            f"- `{r['run_id']}` ({r['task']}): {_cause(r)}. Tool calls: "
            + (", ".join(f"`{c}`" for c in r.get("tool_calls") or []) or "none")
            + "."
        )
    # A cleanup failure leaves pass and valid as scored (CLAUDE_E2E.md) but
    # fails the pytest run, so the summary names it whatever the run scored.
    unclean = [r for r in records if r.get("cleanup_error")]
    if unclean:
        lines += ["", "## Cleanup failures", ""]
        lines += [f"- `{r['run_id']}` ({r['task']}): {r['cleanup_error']}" for r in unclean]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("block", type=Path)
    ap.add_argument("--out", type=Path)
    args = ap.parse_args()
    text = render(load(args.block), args.block.name)
    if args.out:
        args.out.write_text(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
